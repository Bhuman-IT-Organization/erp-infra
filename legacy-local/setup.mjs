#!/usr/bin/env node
/**
 * Stands up a local copy of the legacy ERP so the team can learn what it does.
 *
 * Safety properties, all deliberate:
 *   - The legacy tree on disk is never edited. The container sees a generated
 *     app-config.php bind-mounted over the real one.
 *   - No live credential is written anywhere. Local database credentials are
 *     random per machine, and APP_ENC_KEY is regenerated, so this copy cannot
 *     decrypt secrets stored in the production database.
 *   - The database listens on 127.0.0.1 only, on 33061, so it cannot collide
 *     with a local XAMPP MySQL and is not reachable from the network.
 *   - The client's server is never contacted.
 *
 * Usage:  node setup.mjs [--legacy-root <path>] [--fresh]
 */

import { execFileSync, spawnSync } from 'node:child_process'
import { createHash, randomBytes } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { IMPORT_MARKER_TABLE, countCreateTables, importDecision, mysqlLiteral } from './lib.mjs'

const HERE = dirname(fileURLToPath(import.meta.url))
const argv = process.argv.slice(2)
const argOf = (name, fallback) => {
  const i = argv.indexOf(`--${name}`)
  return i !== -1 && argv[i + 1] ? argv[i + 1] : fallback
}
const FRESH = argv.includes('--fresh')

const LEGACY_ROOT = resolve(argOf('legacy-root', resolve(HERE, '../../erp-legacy/public_html')))
const SOURCE_CONFIG = resolve(LEGACY_ROOT, 'application/config/app-config.php')

// Prefer a full export taken from the client's own phpMyAdmin, which sits beside
// the web root. The dump under sql/ is older and came from a developer machine.
// Override either with --dump <path>.
const DUMP_CANDIDATES = [
  argOf('dump', null),
  resolve(LEGACY_ROOT, '../cubepltech_cube.sql'),
  resolve(LEGACY_ROOT, 'sql/nextgen_latest_live.sql')
].filter(Boolean)
const DUMP = DUMP_CANDIDATES.find((p) => existsSync(p))

const die = (msg) => { console.error(`\n  ${msg}\n`); process.exit(1) }
const step = (msg) => console.log(`  ${msg}`)

// ---------------------------------------------------------------- preflight

console.log('\nLegacy ERP — local setup\n')

if (!existsSync(LEGACY_ROOT)) die(`Legacy tree not found at:\n  ${LEGACY_ROOT}\n\nPass --legacy-root <path> if it lives elsewhere.`)
if (!existsSync(SOURCE_CONFIG)) die(`Not a Perfex install — no application/config/app-config.php under:\n  ${LEGACY_ROOT}`)
if (!DUMP) die(`No database dump found. Looked for:\n${DUMP_CANDIDATES.map((p) => `    ${p}`).join('\n')}\n\n  Pass one with --dump <path>.`)

try { execFileSync('docker', ['--version'], { stdio: 'ignore' }) }
catch { die('Docker is not installed, or not on PATH.') }

// `docker --version` answers even when the engine is down, so ask the engine.
try { execFileSync('docker', ['info'], { stdio: 'ignore' }) }
catch { die('Docker is installed but the engine is not running.\n  Start Docker Desktop, wait for it to say "Engine running", then re-run this.') }

step(`legacy tree  ${LEGACY_ROOT}`)
step(`dump         ${DUMP}`)

// Read only what we need from the real config: the database and schema names,
// so the imported dump matches what the application expects. Credentials and
// the encryption key are deliberately NOT carried over.
const sourceConfig = readFileSync(SOURCE_CONFIG, 'utf8')
const constOf = (name) => (sourceConfig.match(new RegExp(`define\\('${name}',\\s*'([^']*)'`)) || [])[1]
const DB_NAME = constOf('APP_DB_NAME') || 'legacy_local'
const DB_USER = constOf('APP_DB_USERNAME') || 'legacy'
const DB_CHARSET = constOf('APP_DB_CHARSET') || 'utf8mb4'
const DB_COLLATION = constOf('APP_DB_COLLATION') || 'utf8mb4_unicode_ci'

step(`database     ${DB_NAME} (schema name preserved so the app finds it)`)

// ------------------------------------------------------- generated secrets

const envPath = resolve(HERE, '.env')
let DB_PASSWORD, DB_ROOT_PASSWORD, ENC_KEY

if (existsSync(envPath) && !FRESH) {
  const prev = Object.fromEntries(
    readFileSync(envPath, 'utf8').split('\n').filter(Boolean).map((l) => {
      const i = l.indexOf('=')
      return [l.slice(0, i), l.slice(i + 1)]
    })
  )
  DB_PASSWORD = prev.DB_PASSWORD
  DB_ROOT_PASSWORD = prev.DB_ROOT_PASSWORD
  ENC_KEY = prev.LOCAL_ENC_KEY
  step('credentials  reusing the ones in .env')
}

if (!DB_PASSWORD) {
  DB_PASSWORD = randomBytes(18).toString('base64url')
  DB_ROOT_PASSWORD = randomBytes(18).toString('base64url')
  ENC_KEY = randomBytes(16).toString('hex')
  step('credentials  generated fresh (random, local only)')
}

writeFileSync(
  envPath,
  [
    '# Generated by setup.mjs. Local throwaway values. Never commit this file.',
    'COMPOSE_PROJECT_NAME=erp-local',
    `LEGACY_ROOT=${LEGACY_ROOT.replace(/\\/g, '/')}`,
    `DB_NAME=${DB_NAME}`,
    `DB_USER=${DB_USER}`,
    `DB_PASSWORD=${DB_PASSWORD}`,
    `DB_ROOT_PASSWORD=${DB_ROOT_PASSWORD}`,
    `LOCAL_ENC_KEY=${ENC_KEY}`,
    ''
  ].join('\n'),
  'utf8'
)

// ------------------------------------------------- generated app-config.php

writeFileSync(
  resolve(HERE, 'app-config.local.php'),
  `<?php

defined('BASEPATH') or exit('No direct script access allowed');

/*
 * LOCAL DEVELOPMENT CONFIG — generated by workspace/legacy-local/setup.mjs.
 *
 * This file is bind-mounted over application/config/app-config.php inside the
 * container. The real file on disk is never modified.
 *
 * The encryption key below is NOT the production key. Values encrypted by the
 * production system (stored SMTP passwords, integration keys) will therefore
 * fail to decrypt here. That is intended: a local copy must not be able to use
 * production secrets.
 */

// Base URL is derived from the request, exactly as the original config does.
$_app_protocol = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') || (isset($_SERVER['SERVER_PORT']) && $_SERVER['SERVER_PORT'] == 443) ? 'https://' : 'http://';
$_app_host = isset($_SERVER['HTTP_HOST']) ? $_SERVER['HTTP_HOST'] : 'localhost';
$_app_script_name = isset($_SERVER['SCRIPT_NAME']) ? $_SERVER['SCRIPT_NAME'] : '';
$_app_subfolder = substr($_app_script_name, 0, strpos($_app_script_name, '/index.php'));
if (empty($_app_subfolder)) $_app_subfolder = '';
define('APP_BASE_URL', $_app_protocol . $_app_host . $_app_subfolder . '/');

define('APP_ENC_KEY', '${ENC_KEY}');

// 'legacy-db' is the Compose service name. The original says 'localhost', which
// inside a container resolves to the container itself.
define('APP_DB_HOSTNAME', 'legacy-db');
define('APP_DB_USERNAME', '${DB_USER}');
define('APP_DB_PASSWORD', '${DB_PASSWORD}');
define('APP_DB_NAME', '${DB_NAME}');
define('APP_DB_CHARSET', '${DB_CHARSET}');
define('APP_DB_COLLATION', '${DB_COLLATION}');

// Sessions exactly as production does them: the database driver, writing to
// tblsessions. Do not switch this to 'files' -- the php:8.2-apache image ships
// with an empty session.save_path, so the files driver has nowhere to write and
// every login silently bounces back to the login page.
define('SESS_DRIVER', 'database');
define('SESS_SAVE_PATH', 'sessions');
define('APP_SESSION_COOKIE_SAME_SITE', 'Lax');
define('APP_SESSION_EXPIRATION', 28800);
define('APP_SESSION_TIME_TO_UPDATE', 0);

define('APP_PASSWORD_EXPIRY_DAYS', 0);

// Left on, matching production, so local behaviour matches.
define('APP_CSRF_PROTECTION', true);

// The cron guard is broken upstream: APP_CRON_KEY is never defined, so
// defined() short-circuits and /cron/index runs unauthenticated. Defining it
// here closes that hole locally and mirrors the fix recommended to the client.
define('APP_CRON_KEY', '${randomBytes(12).toString('hex')}');
`,
  'utf8'
)
step('wrote        .env and app-config.local.php (both gitignored)')

// --------------------------------------------------------------- run stack

const compose = (args, opts = {}) =>
  spawnSync('docker', ['compose', ...args], { cwd: HERE, stdio: 'inherit', ...opts })

if (FRESH) {
  step('\n  --fresh given: removing the existing database volume')
  compose(['down', '-v'])
}

console.log('\n  Building and starting containers (first run pulls images, a few minutes)...\n')
if (compose(['up', '-d', '--build']).status !== 0) die('docker compose up failed. See the output above.')

// ------------------------------------------------------------ import dump
//
// A completed import is recorded in the `_local_import` table (dump sha256 + table count), and
// only that record makes the next run skip the import (review WR-07). A table count alone would
// call a dump that died half-way "already loaded" forever; the dump has no DROP TABLE statements,
// so an unfinished import can only be fixed with --fresh, and this says so instead of skipping.

// Runs one statement as the database user; credentials stay inside the container's environment.
const query = (sql) => {
  const res = spawnSync(
    'docker',
    ['compose', 'exec', '-T', 'legacy-db', 'sh', '-c',
     'exec mysql -u"$MYSQL_USER" -p"$MYSQL_PASSWORD" "$MYSQL_DATABASE" -N -e "$1"', 'sh', sql],
    { cwd: HERE, encoding: 'utf8' }
  )
  return res.status === 0 ? (res.stdout || '').trim() : null
}

const dump = readFileSync(DUMP)
const dumpSha256 = createHash('sha256').update(dump).digest('hex')
const dumpTables = countCreateTables(dump.toString('latin1'))

const countRow = query(
  `SELECT COUNT(*) FROM information_schema.tables WHERE table_schema = DATABASE() AND table_name <> ${mysqlLiteral(IMPORT_MARKER_TABLE)}`
)
if (countRow === null) die('Could not query legacy-db. Is the container healthy? (docker compose ps)')
const tableCount = parseInt(countRow, 10) || 0

const markerRow = query(
  `SELECT dump_sha256, table_count FROM ${IMPORT_MARKER_TABLE} ORDER BY done_at DESC LIMIT 1`
)
const marker = markerRow ? (([sha, n]) => ({ dumpSha256: sha, tableCount: parseInt(n, 10) }))(markerRow.split('\t')) : null

const recordImport = () => {
  const n = parseInt(query(
    `SELECT COUNT(*) FROM information_schema.tables WHERE table_schema = DATABASE() AND table_name <> ${mysqlLiteral(IMPORT_MARKER_TABLE)}`
  ) || '0', 10)
  const ok = query(
    `CREATE TABLE IF NOT EXISTS ${IMPORT_MARKER_TABLE} (done_at DATETIME NOT NULL, dump_sha256 CHAR(64) NOT NULL, table_count INT NOT NULL); ` +
    `INSERT INTO ${IMPORT_MARKER_TABLE} VALUES (NOW(), ${mysqlLiteral(dumpSha256)}, ${n})`
  )
  if (ok === null) die('Import finished but the completion marker could not be written.')
  step(`recorded     ${n} tables from dump sha256 ${dumpSha256.slice(0, 12)}… in ${IMPORT_MARKER_TABLE}`)
}

const decision = importDecision({ fresh: FRESH, tableCount, dumpTables, dumpSha256, marker })
step(`import       ${decision.action}: ${decision.reason}`)

if (decision.action === 'skip') {
  step('             (use --fresh to reload)')
} else if (decision.action === 'adopt') {
  recordImport()
} else if (decision.action === 'abort') {
  die(`Refusing to reuse this database: ${decision.reason}.\n  Run: node setup.mjs --fresh   (drops the local volume and imports again)`)
} else {
  console.log('\n  Importing the dump...\n')
  const imp = spawnSync(
    'docker',
    ['compose', 'exec', '-T', 'legacy-db', 'mysql', `-u${DB_USER}`, `-p${DB_PASSWORD}`, DB_NAME],
    { cwd: HERE, input: dump, stdio: ['pipe', 'inherit', 'inherit'] }
  )
  if (imp.status !== 0) die('Import failed. See the output above.\n  The database is incomplete; the next run will say so. Fix the cause, then: node setup.mjs --fresh')
  recordImport()
  step('import complete')
}

// ------------------------------------------------------- overlaid modules
//
// Perfex loads only ACTIVATED modules (a tblmodules row with active = 1); the erp_sso overlay
// bind-mounted from erp-infra does nothing without it. Idempotent, so it runs on every setup,
// and a --fresh re-import (which drops the row with the volume) gets it back.

const activation = spawnSync(process.execPath, ['activate-module.mjs', 'erp_sso', '0.1.0'], { cwd: HERE, stdio: 'inherit' })
if (activation.status !== 0) die('Could not activate the erp_sso module on the local database. See the output above.')

console.log(`
  Ready.

    http://localhost:8080/admin/authentication   STAFF login  <- use this
    http://localhost:8080                        client portal (tblcontacts)
    127.0.0.1:33061                              database, user ${DB_USER}

  The two login forms look identical. Staff accounts only work on the /admin
  one; on the other they fail with "Invalid username or password".

  You will need a login. Staff passwords are phppass bcrypt hashes from the
  live system, so use a known account, or reset one:

    node reset-password.mjs <email> <new-password>

  Useful:
    docker compose logs -f legacy  watch errors as you click around
    docker compose down            stop
    node setup.mjs --fresh         wipe the database and reimport
    node ../scripts/local-up.mjs   the full stack (api, web, nginx, redis) on top of this
`)
